let toastTimer = null;
export function toast(msg, { error = false, ms = 4200, free = false } = {}) {
  let el = document.querySelector('.toast');
  if (!el) { el = document.createElement('div'); el.className = 'toast'; el.setAttribute('role', 'status'); document.body.appendChild(el); }
  el.textContent = msg;
  el.classList.toggle('error', !!error);
  el.classList.toggle('top-free', free || !document.querySelector('.deck'));
  el.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { el.hidden = true; }, ms);
}

// Bottom-Sheet; gibt {el, close} zurück
export function sheet(html, { onClose } = {}) {
  closeSheet();
  const bd = document.createElement('div');
  bd.className = 'backdrop';
  bd.innerHTML = `<div class="sheet" role="dialog" aria-modal="true"><div class="grip"></div>${html}</div>`;
  document.body.appendChild(bd);
  const close = () => { if (bd.parentNode) bd.parentNode.removeChild(bd); document.removeEventListener('keydown', onKey); onClose && onClose(); };
  const onKey = (e) => { if (e.key === 'Escape') close(); };
  bd.addEventListener('click', (e) => { if (e.target === bd) close(); });
  document.addEventListener('keydown', onKey);
  bd._close = close;
  const first = bd.querySelector('button, input, select, textarea, a');
  if (first) setTimeout(() => first.focus({ preventScroll: true }), 50);
  return { el: bd.querySelector('.sheet'), close };
}
export function closeSheet() { const bd = document.querySelector('.backdrop'); if (bd && bd._close) bd._close(); }

export function fmtNumber(n) { return Number(n || 0).toLocaleString('de-DE'); }
export function fmtBytes(b) {
  if (!b) return '0 MB';
  if (b < 1e6) return Math.max(1, Math.round(b / 1e3)) + ' KB';
  if (b < 1e9) return (b / 1e6).toFixed(b < 1e7 ? 1 : 0).replace('.', ',') + ' MB';
  return (b / 1e9).toFixed(1).replace('.', ',') + ' GB';
}
export function fmtDuration(sec) {
  sec = Math.round(sec || 0);
  const m = Math.floor(sec / 60), s = sec % 60;
  return m ? `${m}:${String(s).padStart(2, '0')} min` : `${s} s`;
}
export function plural(n, one, many) { return `${fmtNumber(n)} ${n === 1 ? one : many}`; }

export function download(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename; document.body.appendChild(a); a.click();
  setTimeout(() => { URL.revokeObjectURL(url); a.remove(); }, 4000);
}

export function safeFileName(s) {
  return String(s || 'souffleuse').replace(/[\\/:*?"<>|]+/g, '').replace(/\s+/g, ' ').trim().slice(0, 80) || 'souffleuse';
}

export async function copyText(text) {
  try { await navigator.clipboard.writeText(text); return true; } catch (e) {
    const ta = document.createElement('textarea'); ta.value = text; ta.style.position = 'fixed'; ta.style.opacity = '0';
    document.body.appendChild(ta); ta.select();
    let ok = false; try { ok = document.execCommand('copy'); } catch (x) { /* */ }
    ta.remove(); return ok;
  }
}
